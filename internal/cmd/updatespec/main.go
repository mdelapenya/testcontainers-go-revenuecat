// Command updatespec regenerates the bundled Microcks fixture from RevenueCat's
// published REST API v2 reference.
package main

import (
	"bytes"
	"cmp"
	"context"
	"flag"
	"fmt"
	"io"
	"maps"
	"net/http"
	"os"
	"regexp"
	"slices"
	"strconv"
	"strings"
	"time"

	"gopkg.in/yaml.v3"
)

const referenceURL = "https://www.revenuecat.com/docs/api-v2"

type object = map[string]any

func main() {
	output := flag.String("output", "testdata/revenuecat.yaml", "fixture output path")
	flag.Parse()

	ctx, cancel := context.WithTimeout(context.Background(), 2*time.Minute)
	defer cancel()

	spec, count, err := buildFixture(ctx, &http.Client{Timeout: 20 * time.Second})
	if err == nil {
		var data bytes.Buffer
		data.WriteString("# Generated by go generate ./... from " + referenceURL + ".\n")
		encoder := yaml.NewEncoder(&data)
		encoder.SetIndent(2)
		err = encoder.Encode(spec)
		if err == nil {
			err = os.WriteFile(*output, data.Bytes(), 0o644)
		}
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	fmt.Printf("Wrote %d RevenueCat operations to %s\n", count, *output)
}

func buildFixture(ctx context.Context, client *http.Client) (object, int, error) {
	index, err := fetch(ctx, client, referenceURL)
	if err != nil {
		return nil, 0, err
	}
	resourceLink := regexp.MustCompile(`href="/docs/api-v2/([a-z0-9/-]+)"`)
	var resources []string
	for _, match := range resourceLink.FindAllSubmatch(index, -1) {
		resources = append(resources, strings.ReplaceAll(string(match[1]), "/", "-"))
	}
	slices.Sort(resources)
	resources = slices.Compact(resources)
	if len(resources) == 0 {
		return nil, 0, fmt.Errorf("no OpenAPI resource links found at %s", referenceURL)
	}

	paths := object{}
	version := ""
	count := 0
	for _, resource := range resources {
		source := "https://www.revenuecat.com/docs/redocusaurus/openapi-v2-" + resource + ".yaml"
		data, err := fetch(ctx, client, source)
		if err != nil {
			return nil, 0, err
		}
		var spec object
		if err := yaml.Unmarshal(data, &spec); err != nil {
			return nil, 0, fmt.Errorf("parse %s: %w", source, err)
		}

		specVersion, _ := asObject(spec["info"])["version"].(string)
		if version == "" {
			version = specVersion
		}
		if specVersion == "" || specVersion != version {
			return nil, 0, fmt.Errorf("unexpected API version %q in %s", specVersion, source)
		}
		for path, rawPath := range asObject(spec["paths"]) {
			pathItem := asObject(rawPath)
			if paths[path] == nil {
				paths[path] = object{}
			}
			operations := asObject(paths[path])
			for _, method := range []string{"get", "post", "put", "patch", "delete", "head", "options", "trace"} {
				op := asObject(pathItem[method])
				if op == nil {
					continue
				}
				if operations[method] != nil {
					return nil, 0, fmt.Errorf("duplicate %s %s in %s", method, path, source)
				}
				mock, err := mockOperation(spec, path, pathItem, op)
				if err != nil {
					return nil, 0, fmt.Errorf("%s %s in %s: %w", method, path, source, err)
				}
				operations[method] = mock
				count++
			}
		}
	}
	if count == 0 {
		return nil, 0, fmt.Errorf("no operations found in %s", referenceURL)
	}
	ordered, err := orderPaths(paths)
	if err != nil {
		return nil, 0, err
	}
	return object{
		"openapi": "3.1.0",
		"info":    object{"title": "RevenueCat", "version": version},
		"paths":   ordered,
	}, count, nil
}

// Microcks tries path patterns in import order. Put paths with fewer parameters
// first so literals such as /customers/blocked_customers win over /customers/{id}.
func orderPaths(paths object) (*yaml.Node, error) {
	names := slices.Collect(maps.Keys(paths))
	slices.SortFunc(names, func(a, b string) int {
		if order := cmp.Compare(strings.Count(a, "{"), strings.Count(b, "{")); order != 0 {
			return order
		}
		return strings.Compare(a, b)
	})
	node := &yaml.Node{Kind: yaml.MappingNode}
	for _, name := range names {
		var operations yaml.Node
		if err := operations.Encode(paths[name]); err != nil {
			return nil, err
		}
		node.Content = append(node.Content, &yaml.Node{Kind: yaml.ScalarNode, Value: name}, &operations)
	}
	return node, nil
}

var pathParameter = regexp.MustCompile(`\{([^{}]+)\}`)

const success = "success"

func mockOperation(spec object, path string, pathItem, op object) (object, error) {
	operation := object{"operationId": op["operationId"]}
	examplePath := path
	var parameters []object
	var parts []string
	for _, match := range pathParameter.FindAllStringSubmatch(path, -1) {
		name := match[1]
		value := parameterExample(spec, name, pathItem, op)
		examplePath = strings.ReplaceAll(examplePath, match[0], fmt.Sprint(value))
		parts = append(parts, name)
		parameters = append(parameters, object{
			"name": name, "in": "path", "required": true,
			"schema":   object{"type": "string"},
			"examples": namedExample(fmt.Sprint(value)),
		})
	}
	if len(parameters) != 0 {
		operation["parameters"] = parameters
		operation["x-microcks-operation"] = object{
			"dispatcher": "FALLBACK",
			"dispatcherRules": fmt.Sprintf(`{"dispatcher":"URI_PARTS","dispatcherRules":%q,"fallback":%q}`,
				strings.Join(parts, " && "), success),
		}
	}

	responses := asObject(op["responses"])
	var statuses []string
	for status := range responses {
		code, err := strconv.Atoi(status)
		if err == nil && code >= 200 && code < 400 {
			statuses = append(statuses, status)
		}
	}
	if len(statuses) == 0 {
		return nil, fmt.Errorf("no success or redirect response")
	}
	// Prefer success statuses and use redirects when the operation only redirects.
	slices.Sort(statuses)
	status := statuses[0]
	source := dereference(spec, asObject(responses[status]))
	code, _ := strconv.Atoi(status)
	response := object{"description": http.StatusText(code)}
	headers := object{}
	for name, rawHeader := range asObject(source["headers"]) {
		header := dereference(spec, asObject(rawHeader))
		schema := dereference(spec, asObject(header["schema"]))
		value, ok := example(header)
		if !ok {
			value = sample(spec, schema, 0)
		}
		if value != nil {
			headers[name] = object{"schema": schema, "examples": namedExample(value)}
		}
	}
	if len(headers) > 0 {
		response["headers"] = headers
	}
	content := object{}
	for mediaType, rawMedia := range asObject(source["content"]) {
		media := asObject(rawMedia)
		value, ok := example(media)
		if !ok {
			examples := asObject(media["examples"])
			var names []string
			for name := range examples {
				names = append(names, name)
			}
			slices.Sort(names)
			for _, name := range names {
				value, ok = dereference(spec, asObject(examples[name]))["value"]
				if ok {
					break
				}
			}
		}
		if !ok {
			value = sample(spec, asObject(media["schema"]), 0)
		}
		value = singlePage(value)
		if list := asObject(value); list["object"] == "list" {
			if _, exists := list["url"]; exists {
				list["url"] = "/v2" + examplePath
			}
		}
		content[mediaType] = object{"examples": namedExample(value)}
	}
	if len(content) != 0 {
		response["content"] = content
	} else {
		// Microcks links a bodyless response to a named request example.
		response["x-microcks-refs"] = []string{success}
		if len(parameters) == 0 {
			operation["parameters"] = []object{{
				"name": "X-Mock-Example", "in": "header",
				"schema": object{"type": "string"}, "examples": namedExample(success),
			}}
		}
	}
	operation["responses"] = object{status: response}
	return operation, nil
}

func namedExample(value any) object {
	return object{success: object{"value": value}}
}

func parameterExample(spec object, name string, items ...object) any {
	for _, item := range slices.Backward(items) {
		params, _ := item["parameters"].([]any)
		for _, p := range params {
			param := dereference(spec, asObject(p))
			if param["in"] != "path" || param["name"] != name {
				continue
			}
			if value, ok := example(param); ok && value != nil {
				return value
			}
			if value := sample(spec, asObject(param["schema"]), 0); value != nil {
				return value
			}
		}
	}
	return "test_" + name
}

func fetch(ctx context.Context, client *http.Client, address string) ([]byte, error) {
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, address, nil)
	if err != nil {
		return nil, err
	}
	resp, err := client.Do(req)
	if err != nil {
		return nil, fmt.Errorf("fetch %s: %w", address, err)
	}
	defer resp.Body.Close()

	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("fetch %s: %s", address, resp.Status)
	}
	data, err := io.ReadAll(resp.Body)
	if err != nil {
		return nil, fmt.Errorf("read %s: %w", address, err)
	}
	return data, nil
}
